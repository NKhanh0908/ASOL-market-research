    text = content.decode('utf-8', errors='replace')
    entries = []
    for line in text.strip().split('\n'):
        if line.startswith(")]}'"):
            continue
        try:
            data = json.loads(line)
            if not isinstance(data, list):
                continue
            for item in data:
                if isinstance(item, list) and len(item) > 2 and item[0] == 'wrb.fr' and item[1] == 'vyAe2':
                    inner = json.loads(item[2])
                    apps = inner[0][1][0][28][0]
                    seen = set()
                    for idx, app in enumerate(apps):
                        app_info = app[0]
                        pkg = app_info[0][0]
                        if pkg in seen:
                            continue
                        seen.add(pkg)
                        name = app_info[3] if len(app_info) > 3 else None
                        developer = app_info[14] if len(app_info) > 14 else None
                        icon_url = (
                            app_info[1][3][2]
                            if len(app_info) > 1 and len(app_info[1]) > 3 and len(app_info[1][3]) > 2
                            else None
                        )
                        entries.append({
                            'rank': len(seen),
                            'package': pkg,
                            'name': name,
                            'developer': developer,
                            'icon_url': icon_url,
                            'store_url': f'https://play.google.com/store/apps/details?id={pkg}',
                        })
        except Exception:
            pass
    return entries


